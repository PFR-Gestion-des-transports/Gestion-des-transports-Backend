package gestiontransports.enums;

/**
 * Type de motorisation d'un véhicule.
 */
public enum Motorisation {

    /** Véhicule propulsé uniquement par un moteur électrique. */
    ELECTRIQUE,

    /** Véhicule équipé d'un moteur à combustion interne fonctionnant à l'essence. */
    ESSENCE,

    /** Véhicule combinant un moteur thermique et un moteur électrique. */
    HYBRIDE
}
